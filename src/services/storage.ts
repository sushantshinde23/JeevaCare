const LOCAL_STORAGE_KEYS = {
  REFERRALS: 'matricare_db_referrals',
  FACILITIES: 'matricare_db_facilities',
  TRANSPORTS: 'matricare_db_transports',
  NOTIFICATIONS: 'matricare_db_notifications',
  OFFLINE_DRAFTS: 'matricare_offline_drafts',
  CURRENT_USER: 'matricare_current_user',
};

// Safe local persistence loader
export function loadStoredData<T>(key: string, fallback: T): T {
  try {
    const raw = localStorage.getItem(key);
    if (raw) {
      return JSON.parse(raw);
    }
  } catch {
    // fallback
  }
  return fallback;
}

export function saveStoredData<T>(key: string, data: T): void {
  try {
    localStorage.setItem(key, JSON.stringify(data));
  } catch {
    // ignore
  }
}

// Offline queue helpers
export function getOfflineDrafts(): Referral[] {
  return loadStoredData<Referral[]>(LOCAL_STORAGE_KEYS.OFFLINE_DRAFTS, []);
}

export function saveOfflineDraft(draft: Referral): void {
  const drafts = getOfflineDrafts();
  const existingIndex = drafts.findIndex((d) => d.id === draft.id);
  if (existingIndex >= 0) {
    drafts[existingIndex] = draft;
  } else {
    drafts.push(draft);
  }
  saveStoredData(LOCAL_STORAGE_KEYS.OFFLINE_DRAFTS, drafts);
}

export function removeOfflineDraft(id: string): void {
  const drafts = getOfflineDrafts().filter((d) => d.id !== id);
  saveStoredData(LOCAL_STORAGE_KEYS.OFFLINE_DRAFTS, drafts);
}
